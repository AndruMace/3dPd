// Generates TS constant tables from the original sources: ItemSpriteSheet indices and Assets sound names.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { GENERATED, PD_SRC } from './paths.ts';

function intConstants(file: string): [string, number][] {
  const src = readFileSync(path.join(PD_SRC, file), 'utf8');
  return [...src.matchAll(/public static final int\s+(\w+)\s*=\s*(\d+)\s*;/g)].map((m) => [m[1], Number(m[2])]);
}

function stringConstants(file: string): [string, string][] {
  const src = readFileSync(path.join(PD_SRC, file), 'utf8');
  return [...src.matchAll(/public static final String\s+(\w+)\s*=\s*"([^"]+)"\s*;/g)].map((m) => [m[1], m[2]]);
}

const header = '// Generated by tools/extract-constants.ts from the original Pixel Dungeon sources. Do not edit.\n';
mkdirSync(GENERATED, { recursive: true });

const items = intConstants('sprites/ItemSpriteSheet.java');
writeFileSync(
  path.join(GENERATED, 'ItemSpriteSheet.ts'),
  `${header}export const ItemSpriteSheet = {\n${items.map(([k, v]) => `  ${k}: ${v},`).join('\n')}\n} as const;\n`,
);

const assets = stringConstants('Assets.java');
writeFileSync(
  path.join(GENERATED, 'Assets.ts'),
  `${header}export const Assets = {\n${assets.map(([k, v]) => `  ${k}: '${v}',`).join('\n')}\n} as const;\n`,
);
console.log(`wrote ${items.length} item sprite indices, ${assets.length} asset names`);
